"""Generate installable layout files from a full keymap.

Usage:
    python -m kbeval.export                       # keymaps/italian-dvorak-v2.json -> dist/

Writes:
    dist/xkb/itdvorak                    XKB symbols file (Linux: Wayland and X11)
    dist/keybr/it_dvorak_v2.json         keybr layout with the accent dead key
    dist/keybr/it_dvorak_v2_simple.json  keybr layout without dead keys
"""

from __future__ import annotations

import argparse
import json
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Physical key (KeyboardEvent.code) -> XKB key name, in keyboard order.
XKB_KEYS = {
    "Backquote": "TLDE",
    **{f"Digit{d}": f"AE{i:02d}" for i, d in enumerate("1234567890", 1)},
    "Minus": "AE11", "Equal": "AE12",
    **{f"Key{c}": f"AD{i:02d}" for i, c in enumerate("QWERTYUIOP", 1)},
    "BracketLeft": "AD11", "BracketRight": "AD12",
    **{f"Key{c}": f"AC{i:02d}" for i, c in enumerate("ASDFGHJKL", 1)},
    "Semicolon": "AC10", "Quote": "AC11", "Backslash": "BKSL",
    "IntlBackslash": "LSGT",
    **{f"Key{c}": f"AB{i:02d}" for i, c in enumerate("ZXCVBNM", 1)},
    "Comma": "AB08", "Period": "AB09", "Slash": "AB10",
}

# Physical key -> (row, col) in the kbeval keyboard model.
POSITIONS = {
    **{f"Digit{d}": (-1, i) for i, d in enumerate("1234567890")},
    "Minus": (-1, 10), "Equal": (-1, 11),
    **{f"Key{c}": (0, i) for i, c in enumerate("QWERTYUIOP")},
    "BracketLeft": (0, 10), "BracketRight": (0, 11),
    **{f"Key{c}": (1, i) for i, c in enumerate("ASDFGHJKL")},
    "Semicolon": (1, 9), "Quote": (1, 10), "Backslash": (1, 11),
    **{f"Key{c}": (2, i) for i, c in enumerate("ZXCVBNM")},
    "Comma": (2, 7), "Period": (2, 8), "Slash": (2, 9),
}

KEYSYMS = {
    " ": "space", "!": "exclam", '"': "quotedbl", "#": "numbersign", "$": "dollar", "%": "percent",
    "&": "ampersand", "'": "apostrophe", "(": "parenleft", ")": "parenright", "*": "asterisk",
    "+": "plus", ",": "comma", "-": "minus", ".": "period", "/": "slash", ":": "colon",
    ";": "semicolon", "<": "less", "=": "equal", ">": "greater", "?": "question", "@": "at",
    "[": "bracketleft", "\\": "backslash", "]": "bracketright", "^": "asciicircum", "_": "underscore",
    "`": "grave", "{": "braceleft", "|": "bar", "}": "braceright", "~": "asciitilde",
    "£": "sterling", "§": "section", "°": "degree", "€": "EuroSign",
    "à": "agrave", "è": "egrave", "é": "eacute", "ì": "igrave", "ò": "ograve", "ù": "ugrave",
    "À": "Agrave", "È": "Egrave", "É": "Eacute", "Ì": "Igrave", "Ò": "Ograve", "Ù": "Ugrave",
}

DEAD = {"dead_grave": "`", "dead_acute": "´"}


def keysym(symbol: str) -> str:
    if symbol in DEAD:
        return symbol
    if len(symbol) != 1:
        raise ValueError(f"unknown symbol {symbol!r}")
    if symbol.isascii() and symbol.isalnum():
        return symbol
    return KEYSYMS.get(symbol, f"U{ord(symbol):04X}")


def xkb_symbols(spec: dict) -> str:
    lines = [
        "// Italian Dvorak: a Dvorak-style layout optimised for Italian.",
        "// Generated by `python -m kbeval.export` from keymaps/; do not edit by hand.",
        "// https://github.com/FabioCuccaro/italian_dvorak",
        "",
        'default partial alphanumeric_keys modifier_keys',
        'xkb_symbols "basic" {',
        f'    name[Group1] = "{spec["name"]}";',
        "",
    ]
    for code, xkb in XKB_KEYS.items():
        symbols = spec["keys"].get(code)
        if not symbols:
            continue
        syms = ", ".join(f"{keysym(s):<12}" for s in symbols).rstrip()
        lines.append(f"    key <{xkb}> {{ [ {syms} ] }};")
    lines += ["", '    include "level3(ralt_switch)"', "};", ""]
    return "\n".join(lines)


def keybr_layout(spec: dict, dead_keys: bool) -> dict:
    """keybr importKeymap format: two levels per key, dead keys as "*<accent>"."""
    out = {}
    for code in XKB_KEYS:
        symbols = spec["keys"].get(code)
        if not symbols:
            continue
        base, shift = symbols[0], symbols[1]
        if base in DEAD:
            out[code] = ["*" + DEAD[base], "*" + DEAD[shift]] if dead_keys else "'\""
        else:
            out[code] = base + shift
    return out


def check_against_layout(spec: dict, layout_path: Path):
    """Every character of the scored layout must sit on the same physical key."""
    layout = json.loads(layout_path.read_text(encoding="utf-8"))
    rows = {"top": 0, "home": 1, "bottom": 2}
    placed = {}
    for name, chars in layout["rows"].items():
        for col, ch in enumerate(chars):
            if ch != "_":
                placed[ch] = (rows[name], col)
    for ch, spec_key in layout.get("extra", {}).items():
        row, col = spec_key.split(":")
        placed[ch] = ({"number": -1, **rows}[row], int(col))
    if layout["accents"]["method"] == "deadkey":
        row, col = layout["accents"]["key"].split(":")
        placed["dead_grave"] = ({"number": -1, **rows}[row], int(col))
    by_position = {pos: code for code, pos in POSITIONS.items()}
    for ch, pos in placed.items():
        code = by_position[pos]
        if spec["keys"][code][0] != ch:
            raise ValueError(f"{ch!r} is on {code} in {layout_path.name} but the keymap has "
                             f"{spec['keys'][code][0]!r} there")


def main(argv=None):
    p = argparse.ArgumentParser(prog="kbeval.export", description="Generate installable layout files.")
    p.add_argument("--keymap", type=Path, default=ROOT / "keymaps" / "italian-dvorak-v2.json")
    p.add_argument("--out", type=Path, default=ROOT / "dist")
    args = p.parse_args(argv)

    spec = json.loads(args.keymap.read_text(encoding="utf-8"))
    for code, symbols in spec["keys"].items():
        if code not in XKB_KEYS:
            raise ValueError(f"unknown key {code}")
        for s in symbols:
            if s not in DEAD and unicodedata.normalize("NFC", s) != s:
                raise ValueError(f"{code}: {s!r} is not NFC")
    check_against_layout(spec, ROOT / spec["layout"])

    (args.out / "xkb").mkdir(parents=True, exist_ok=True)
    (args.out / "keybr").mkdir(parents=True, exist_ok=True)
    (args.out / "xkb" / "itdvorak").write_text(xkb_symbols(spec), encoding="utf-8")
    for name, dead in (("it_dvorak_v2.json", True), ("it_dvorak_v2_simple.json", False)):
        text = json.dumps(keybr_layout(spec, dead), ensure_ascii=False, indent=2) + "\n"
        (args.out / "keybr" / name).write_text(text, encoding="utf-8")
    print(f"Wrote {args.out}/xkb/itdvorak and {args.out}/keybr/")


if __name__ == "__main__":
    main()
